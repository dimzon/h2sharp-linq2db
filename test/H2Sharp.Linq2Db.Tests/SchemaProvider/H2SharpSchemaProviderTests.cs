using LinqToDB;
using LinqToDB.Data;
using LinqToDB.SchemaProvider;

using Xunit;

namespace H2Sharp.Linq2Db.Tests.SchemaProvider;

/// <summary>
///     The catalogue of the database, read the way H2 2.5 keeps it.
/// </summary>
/// <remarks>
///     <para>
///         These are the PostgreSQL tests of linq2db, carried over to H2: the same checks, but
///         the answers are H2's, and the SQL is H2's.
///     </para>
/// </remarks>
public class H2SharpSchemaProviderTests
{
    [Fact]
    public async Task The_catalogue_lists_the_tables_and_their_columns()
    {
        await using var db = H2SharpDatabase.Open(nameof(The_catalogue_lists_the_tables_and_their_columns));

        await db.ExecuteAsync(
            """
            CREATE TABLE "Rows" (
                "Id" integer NOT NULL,
                "Name" varchar(50) NOT NULL,
                "Price" numeric(10,2) NOT NULL,
                CONSTRAINT "PK_Rows" PRIMARY KEY ("Id")
            )
            """);

        var schema = db.DataProvider.GetSchemaProvider().GetSchema(db);

        var table = Assert.Single(schema.Tables, t => t.TableName == "Rows");

        Assert.Equal("PUBLIC", table.SchemaName);
        Assert.False(table.IsView);

        Assert.Collection(
            table.Columns,
            column =>
            {
                Assert.Equal("Id", column.ColumnName);
                Assert.Equal(DataType.Int32, column.DataType);
                Assert.False(column.IsNullable);
                Assert.True(column.IsPrimaryKey);
                Assert.Equal(0, column.PrimaryKeyOrder);
            },
            column =>
            {
                Assert.Equal("Name", column.ColumnName);
                Assert.Equal(DataType.NVarChar, column.DataType);
                Assert.Equal(50, column.Length);
                Assert.False(column.IsNullable);
            },
            column =>
            {
                Assert.Equal("Price", column.ColumnName);
                Assert.Equal(DataType.Decimal, column.DataType);
                Assert.Equal(10, column.Precision);
                Assert.Equal(2, column.Scale);
                Assert.False(column.IsNullable);
            });
    }

    [Fact]
    [Trait("Category", "BlockedByPort")]
    public async Task The_catalogue_carries_the_comments()
    {
        await using var db = H2SharpDatabase.Open(nameof(The_catalogue_carries_the_comments));

        await db.ExecuteAsync(
            """
            CREATE TABLE "Rows" (
                "Id" integer NOT NULL,
                CONSTRAINT "PK_Rows" PRIMARY KEY ("Id")
            )
            """);

        await db.ExecuteAsync("COMMENT ON TABLE \"Rows\" IS 'This is the Rows table'");
        await db.ExecuteAsync("COMMENT ON COLUMN \"Rows\".\"Id\" IS 'This is the Rows.Id column'");

        var schema = db.DataProvider.GetSchemaProvider().GetSchema(db);

        var table = Assert.Single(schema.Tables, t => t.TableName == "Rows");

        Assert.Equal("This is the Rows table", table.Description);
        Assert.Equal("This is the Rows.Id column", Assert.Single(table.Columns).Description);
    }

    [Fact]
    [Trait("Category", "BlockedByPort")]
    public async Task The_catalogue_knows_an_identity_column()
    {
        await using var db = H2SharpDatabase.Open(nameof(The_catalogue_knows_an_identity_column));

        await db.ExecuteAsync(
            """
            CREATE TABLE "Rows" (
                "Id" integer GENERATED BY DEFAULT AS IDENTITY,
                "Name" varchar(50)
            )
            """);

        var schema = db.DataProvider.GetSchemaProvider().GetSchema(db);

        var table = Assert.Single(schema.Tables, t => t.TableName == "Rows");
        var id    = table.Columns.First(c => c.ColumnName == "Id");

        Assert.True(id.IsIdentity);
        Assert.True(id.SkipOnInsert);
    }

    [Fact]
    [Trait("Category", "BlockedByPort")]
    public async Task The_catalogue_links_a_reference_to_the_table_it_points_at()
    {
        await using var db = H2SharpDatabase.Open(nameof(The_catalogue_links_a_reference_to_the_table_it_points_at));

        await db.ExecuteAsync(
            """
            CREATE TABLE "Parents" (
                "Id" integer NOT NULL,
                CONSTRAINT "PK_Parents" PRIMARY KEY ("Id")
            )
            """);

        await db.ExecuteAsync(
            """
            CREATE TABLE "Children" (
                "Id" integer NOT NULL,
                "ParentId" integer,
                CONSTRAINT "PK_Children" PRIMARY KEY ("Id"),
                CONSTRAINT "FK_Children_Parents" FOREIGN KEY ("ParentId") REFERENCES "Parents" ("Id")
            )
            """);

        var schema = db.DataProvider.GetSchemaProvider().GetSchema(db);

        var children = Assert.Single(schema.Tables, t => t.TableName == "Children");
        var parents  = Assert.Single(schema.Tables, t => t.TableName == "Parents");

        var foreignKey = Assert.Single(children.ForeignKeys);

        Assert.Equal("FK_Children_Parents", foreignKey.KeyName);
        Assert.Equal(parents, foreignKey.OtherTable);
        Assert.Equal("ParentId", Assert.Single(foreignKey.ThisColumns).ColumnName);
        Assert.Equal("Id", Assert.Single(foreignKey.OtherColumns).ColumnName);
    }

    [Fact]
    public async Task The_catalogue_leaves_its_own_tables_out()
    {
        await using var db = H2SharpDatabase.Open(nameof(The_catalogue_leaves_its_own_tables_out));

        await db.ExecuteAsync("CREATE TABLE \"Rows\" (\"Id\" integer NOT NULL)");

        var schema = db.DataProvider.GetSchemaProvider().GetSchema(db);

        Assert.DoesNotContain(schema.Tables, t => t.SchemaName == "INFORMATION_SCHEMA");
    }
}
