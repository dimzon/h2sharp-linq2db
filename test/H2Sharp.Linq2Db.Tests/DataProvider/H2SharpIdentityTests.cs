using System;
using System.Data.Common;

using LinqToDB;
using LinqToDB.Data;
using LinqToDB.Interceptors;
using LinqToDB.Mapping;

using Xunit;

namespace H2Sharp.Linq2Db.Tests.DataProvider;

/// <summary>
/// The identity column: the DDL of it, and the statement that reads the value back.
/// </summary>
/// <remarks>
/// H2 2.5 has no <c>RETURNING</c> — the reference refuses the clause — and no
/// <c>SCOPE_IDENTITY()</c>, no <c>IDENTITY()</c> and no <c>LAST_INSERT_ID()</c> either. The row
/// the insert made is read through <c>FINAL TABLE</c>, which is the form the H2 grammar has for
/// it, and the provider writes the insert that way.
/// </remarks>
public class H2SharpIdentityTests
{
    [Table("IdentityRows")]
    public class IdentityRow
    {
        [Column("Id", IsPrimaryKey = true, SkipOnInsert = true)]
        public int Id { get; set; }

        [Column("Name")]
        public string Name { get; set; } = "";
    }

    [Fact]
    public void The_insert_that_returns_the_generated_key_is_written_the_way_H2_writes_it()
    {
        using var db = H2SharpDatabase.Open(nameof(The_insert_that_returns_the_generated_key_is_written_the_way_H2_writes_it));

        db.Execute("""
            CREATE TABLE "IdentityRows" (
                "Id" integer GENERATED BY DEFAULT AS IDENTITY,
                "Name" varchar(50)
            )
            """);

        SqlRecorder recorder = new();
        db.AddInterceptor(recorder);

        // The engine does not read FINAL TABLE yet, so the insert cannot run; the statement
        // is what this test is about, and the recorder has it whether the engine ran it or not.
        // The statement is what this test is about, and the recorder has it whether the
        // engine ran it or not.
        _ = Record.Exception(() => db.InsertWithIdentity<IdentityRow>(new IdentityRow { Name = "x" }));

        Assert.Equal(
            """
            SELECT "Id" FROM FINAL TABLE (INSERT INTO "IdentityRows"
            (
            	"Name"
            )
            VALUES
            (
            	$Name
            )
            )
            """.ReplaceLineEndings("\n"),
            recorder.Text!.ReplaceLineEndings("\n"));
    }

    [Fact]
    public void The_generated_key_comes_back_from_the_insert()
    {
        using var db = H2SharpDatabase.Open(nameof(The_generated_key_comes_back_from_the_insert));

        db.Execute("""
            CREATE TABLE "IdentityRows" (
                "Id" integer GENERATED BY DEFAULT AS IDENTITY,
                "Name" varchar(50)
            )
            """);

        object id = db.InsertWithIdentity<IdentityRow>(new IdentityRow { Name = "x" });

        Assert.Equal(1, id);
    }

    /// <summary>
    /// Records the statements the provider sends, so that a test can say what the provider
    /// wrote without waiting for the engine to run it.
    /// </summary>
    private sealed class SqlRecorder : CommandInterceptor
    {
        public string? Text { get; private set; }

        public override DbCommand CommandInitialized(CommandEventData eventData, DbCommand command)
        {
            Text = command.CommandText;
            return command;
        }
    }
}
